
def show_breakfast_instructions():
    print("\n===== BREAKFAST INSTRUCTIONS =====")

    print("1. Collect two eggs and two slices of bread.")
    print("2. Collect salt, cooking oil, a frying pan and a spatula.")
    print("3. Crack the eggs into a clean bowl.")
    print("4. Add a small amount of salt and whisk the eggs.")
    print("5. Place the frying pan on the stove.")
    print("6. Add cooking oil and heat the pan.")
    print("7. Pour the eggs into the pan.")
    print("8. Cook until the eggs are fully set.")
    print("9. Remove the eggs using a spatula.")
    print("10. Toast the bread.")
    print("11. Place the eggs between the bread slices.")
    print("12. Serve the breakfast on a clean plate.")

    print("\nBreakfast preparation instructions completed.")


if __name__ == "__main__":
    show_breakfast_instructions()
